#!/usr/bin/env python3
"""Rebuild exact T1E2 DSP from two user-supplied official firmware files.

No cached firmware, donor routines, compiled objects, or private bank are inputs.
All intermediate firmware and extracted donor code stay in the explicit work dir.
"""
import argparse
import contextlib
import hashlib
import importlib
import importlib.util
import json
import os
from pathlib import Path
import shutil
import sys

sys.dont_write_bytecode = True

from placements import L1_ROWS, FUNCTION_POINTER_DATA
from stages import STAGES

HERE = Path(__file__).resolve().parent
V7 = Path('firmware/ghidra/oneshot-proof/v7-source')
FINAL_SHA = '409811b1776c9a2cf1c73e5fce2f5dbcf7378c9fd6f835f45ba1a0e97c1a3cc3'


def sha(data):
    return hashlib.sha256(data).hexdigest()


def checked(path, expected):
    data = path.read_bytes()
    actual = sha(data)
    if actual != expected:
        raise ValueError(f'{path}: expected {expected}, got {actual}')
    return data


def write(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)


def dump(path, value):
    write(path, (json.dumps(value, indent=2) + '\n').encode())


def module(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    obj = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(obj)
    return obj


def base(work, dn2, dt2):
    from dnfw.firmware.load import load
    from dnfw.transplant import plan, oneshot_dt2
    from dnfw.oneshot import build as OB, samples
    from dnfw.image import bootstream as B, sharc_object as O
    import sharc_waverider_m3 as A
    import sharc_waverider_render as M

    native = load(dn2).container.find(7).unpack()
    donor = load(dt2).container.find(7).unpack()
    write(work/'firmware/dn2-1.11/section_7_blob.bin', native)
    write(work/'firmware/dt2-1.16/section_7_blob.bin', donor)
    p = plan.build(oneshot_dt2.SPEC, dt2, dn2)
    if not p.ok:
        raise ValueError(p.refusals)
    gen = module(work/V7/'scripts/gen_oneshot_sharc.py', 'generate_v7_adapter')
    assembler = work/'assembler'
    assembler.mkdir()
    parcels, labels, offsets = gen.assemble(gen.SOURCE.read_text(), assembler)
    fixed, wrong = gen.targets(gen.SOURCE.read_text(), labels)
    if wrong:
        raise ValueError(f'Original adapter branch labels changed: {wrong}')
    adapter = O.load_bytes(parcels)
    entry, _ = A._selas_line('JUMP 0x185800;', assembler)
    # Historical proof WAV was generated by samples.chirp(), then passed
    # through sample.from_wav(): signed16 / 32768, then round(*32767).
    pcm = [round(v / 32768 * 32767) for v in samples.chirp()]
    result, _ = OB.section7(native, p, adapter, [pcm], entry_jump=O.load_bytes(entry))
    early, _ = A._selas_line(f"JUMP {labels['os_handoff_early_guard.']:#x};", assembler)
    image = bytearray(result)
    if B.read_span(result, 0x283850e4, 6) != bytes.fromhex('0e0700001600'):
        raise ValueError('Official early-copy branch mismatch')
    B.write_span(image, 0x283850e4, O.load_bytes(early))
    path = work/V7/'out/os1handoff-v7/section_7.bin'
    write(path, image)
    checked(path, 'b5b568a86d93041a0110a8df83cf17ad5a586d9b93c40882da40fb622a01bcb9')
    # Offset metadata only. No compiled adapter JSON is supplied by the release.
    dump(work/V7/'csrc/oneshot/sharc/oneshot5.json', {'instruction_offsets': offsets})
    bank = work/'firmware/ghidra/storage-proof/bank-loader-v2'
    (bank/'attempts').mkdir()
    module(bank/'src/build_loader.py', 'bank_loader').main()
    checked(bank/'section_7.bin', 'fb4a5261a0396ed970fe267af06acd152037d084390175676d683cc064ed0429')

    # These standalone assemblers' historical main() also opened unrelated
    # old firmware/evidence. Their assemble() functions need only source.
    root = work/'output/dn2-research'
    for folder, output, expected in (
        ('oneshot-live-controls-20261008', 'controls.bin', '27a92746523ed3450868e864b34244446bfebb45a7814a32e140a67a19c66734'),
        ('oneshot-live-level-20261008', 'level.bin', '7d73a600baed4091a546e0260ce92696a48fd09f87dd7e4cb95a23b47cb27819')):
        m = module(root/folder/'build.py', folder.replace('-', '_'))
        code, offs, syms = m.assemble()
        write(root/folder/output, code)
        checked(root/folder/output, expected)
        dump(root/folder/'build-receipt.json', {'instruction_offsets': offs,
             'sha256': sha(code), 'purpose': 'Rebuilt original assembler output; not a hardware-test receipt'})
    write(root/'oneshot-live-level-20261008/state-and-save-zero.bin', bytes(104))
    memory = M.Digikit(None).ldr.LoadedMemory.from_stream(donor)
    kb = root/'oneshot-keyboard-dsp-v2-20261008'
    write(kb/'baseline-section7.bin', (bank/'section_7.bin').read_bytes())
    write(kb/'float-to-int64.bin', memory.read_sw(0xb88f06, 212))
    write(root/'oneshot-native-bounds-dt2-20261008/int64-to-float-native.bin', memory.read_sw(0xb88f70, 244))
    module(kb/'build.py', 'keyboard').main()
    checked(kb/'section_7.bin', '77a8cd4bace91b5a0bfc243713cd2b5e5da7881912fbe06a3b54c60a963a2c08')
    bounds = root/'oneshot-native-bounds-dsp-v2-20261008'
    module(bounds/'build.py', 'bounds').main()
    checked(bounds/'section_7.bin', '6c9658f6c7020a0b303e7f85b4b8f3deb1fd713c27fce94c9eebf4c7dcd3fe9e')


def inventory(work):
    rows = []
    for original in L1_ROWS:
        row = dict(original)
        field = row.pop('producer_offsets_field', None)
        if field:
            row['instruction_offsets'] = json.loads((work/row['producer']).read_text())[field]
        rows.append(row)
    dump(work/'output/dn2-research/dt2-samplers-t1dc-20261010/l1-imported-code-inventory.json',
         {'section7_sha256': 'f4db86c53e7247fd914e042b6d9fae9605639fbf4c50634cac784846423f4d12',
          'active_or_conservatively_retained_code': rows,
          'function_pointer_data': FUNCTION_POINTER_DATA})


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--dn2', type=Path, required=True)
    p.add_argument('--dt2', type=Path, required=True)
    p.add_argument('--work', type=Path, required=True)
    p.add_argument('--dnfw-src', type=Path, default=HERE.parent/'tools/dnfw/src')
    p.add_argument('--digikit', type=Path, required=True)
    p.add_argument('--selas', type=Path, required=True)
    args = p.parse_args()
    dn2, dt2 = args.dn2.read_bytes(), args.dt2.read_bytes()
    checked(args.dn2, '2af43e65e3d8390b41c9f66222620f8cce027d73ed87db00c80b440f628472e0')
    if not (args.dnfw_src/'dnfw').is_dir() or not (args.digikit/'tools/sharc_trace.py').is_file():
        p.error('Required source toolchain is missing')
    if not args.selas.is_file():
        p.error('SHARC assembler executable is missing')
    work = args.work.resolve()
    if work.exists():
        p.error('--work must be a fresh directory')
    release_root = HERE.parents[1]
    if release_root == work or release_root in work.parents:
        p.error('Build output must be outside the release source tree')
    os.environ['SELAS'] = str(args.selas.resolve())
    os.environ['DSP_RELEASE_SELAS'] = str(args.selas.resolve())
    os.environ['DIGIKIT'] = str(args.digikit.resolve())
    shutil.copytree(HERE/'sources', work)
    sys.path[:0] = [str(args.dnfw_src.resolve()), str(HERE/'support'), str(work/'scripts')]
    with (work/'build.log').open('w') as log:
        with contextlib.redirect_stdout(log):
            base(work, dn2, dt2)
        print('Base DSP matches native-bounds-v2', flush=True)
        receipts = []
        for name, folder, expected in STAGES:
            m = importlib.import_module(name)
            target = work/'output/dn2-research'/folder
            with contextlib.redirect_stdout(log):
                if name == 'build_dt2_dsp_l1_code_fix':
                    inventory(work)
                if name == 'build_dt2_dsp_fatal_diagnostic':
                    previous = work/'output/dn2-research/dt2-dsp-render-diagnostic-20261010/section_7.bin'
                    m.build(target, base=previous, base_sha=receipts[-1]['sha256'])
                else:
                    m.build(target)
            checked(target/'section_7.bin', expected)
            receipts.append({'stage': name, 'sha256': expected})
            print(f'{name}: {expected[:12]}', flush=True)
    final = work/'output/dn2-research'/STAGES[-1][1]/'section_7.bin'
    write(work/'section_7.bin', checked(final, FINAL_SHA))
    dump(work/'rebuild.json', {'schema': 't1e2-dsp-source-rebuild-v1',
         'inputs': {'dn2_sha256': sha(dn2), 'dt2_sha256': sha(dt2)},
         'section7_sha256': FINAL_SHA, 'stages': receipts,
         'hardware_access': False, 'private_sample_bank_required': False})
    print(f'Exact T1E2 DSP: {work/"section_7.bin"}', flush=True)


if __name__ == '__main__':
    main()
